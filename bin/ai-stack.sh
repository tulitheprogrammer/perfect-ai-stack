#!/usr/bin/env bash
set -euo pipefail

# ai-stack — Docker-based AI proxy stack
# LiteLLM (+ Headroom compression) + Lore run in Docker; lat.md knowledge
# graph scaffolded per-repo with a git pre-commit hook for doc enforcement.

# Resolve $0 through symlinks: npx/npm invoke the bin via a symlink in
# node_modules/.bin, so dirname"$0" would be that .bin dir and ".." would
# land in node_modules (no docker-compose.yml there). Follow the chain to the
# real script inside the package, then the stack root is one level up.
SCRIPT="$0"
while [ -L "$SCRIPT" ]; do
  TARGET="$(readlink "$SCRIPT")"
  case "$TARGET" in
    /*) SCRIPT="$TARGET" ;;
    *)  SCRIPT="$(cd "$(dirname "$SCRIPT")" && pwd)/$TARGET" ;;
  esac
done
DIR="$(cd "$(dirname "$SCRIPT")/.." && pwd)"
CMD="${1:-help}"

wizard() {
  # `read`/`read -n1` fail on non-TTY stdin (EOF), and under `set -e` that
  # kills the wizard silently mid-flow. Fail loudly instead.
  if [ ! -t 0 ]; then
    echo "  The wizard is interactive — run it in a terminal."
    exit 1
  fi
  # .env is written to the STACK dir ($DIR) regardless of where you invoke the
  # wizard, because docker compose only auto-loads .env from the directory
  # holding docker-compose.yml. Writing it to the caller's project (the old
  # behaviour) produced a .env that was silently never read. Shell exports need
  # no file at all, so this is the only case where the location matters.
  if [ "$PWD" != "$DIR" ]; then
    echo "  Note: a .env written here lands in the stack dir, not this project:"
    echo "    $DIR/.env"
    echo "  (docker compose only auto-loads .env from its own dir.) Prefer just"
    echo "  exporting the key in your shell profile — no file needed."
    echo ""
  fi
  echo "┌─────────────────────────────────────────────┐"
  echo "│  perfect-ai-stack — Setup Wizard             │"
  echo "└─────────────────────────────────────────────┘"
  echo ""

  MISSING=""

  # Both API keys are OPTIONAL — a local-only stack (Ollama) needs neither, and
  # nobody needs both. So these checks are informational: they report what the
  # wizard found without ever blocking on a key for a provider you don't use.
  report_var() {
    local name="$1" alt="$2"
    local val
    val="$(eval echo \$$name 2>/dev/null || true)"
    if [ -n "$val" ]; then
      echo "  $name is set"
    elif [ -n "$alt" ] && [ -n "$(eval echo \$$alt 2>/dev/null || true)" ]; then
      echo "  $name is set (via $alt)"
    else
      echo "  $name is not set"
      MISSING="$MISSING $name"
    fi
  }

  # DEEPSEEK_API_KEY is canonical; OPENAI_API_KEY is the legacy name
  # (docker-compose.yml sets both, each falling back to the other), so either
  # satisfies it. Never report a legacy-only export as missing — the wizard
  # would then offer to re-persist a key that already works.
  report_var "ANTHROPIC_API_KEY" ""
  report_var "DEEPSEEK_API_KEY" "OPENAI_API_KEY"

  echo ""
  # The menu is offered even when every key is already set, because `wizard`
  # means "write me a .env" — exiting early made the command silently do nothing
  # in exactly the case where the user asked for a file. Keys already exported
  # are still skipped by prompt_var, so no duplicate lines are written; the
  # shell export stays the source of truth.
  if [ -z "$MISSING" ]; then
    echo "  All keys are already set in your environment."
    echo "  Nothing further is needed — a .env is optional. Continuing in case you"
    echo "  want one for other variables."
  else
    echo "  Not set:$MISSING — both are optional (needed only for Claude / DeepSeek)."
    echo "  Press Enter to skip any you don't use — a local-only stack needs neither."
  fi

  echo ""
  echo "  1) Print export commands (copy-paste into terminal)"
  echo "  2) Save to .env file (STACK dir, where docker compose auto-loads it)"
  echo "  3) Both"
  echo "  4) Do nothing — keys are already in my environment"
  echo ""
  # Single-keypress choice: reads one digit, no Enter required.
  printf "  Choose [1/2/3/4] (default: 1): "
  IFS= read -r -n1 CHOICE_KEY
  echo ""
  # Empty (Enter/EOF) -> default 1.
  CHOICE="${CHOICE_KEY:-1}"

  # 4 = leave the environment alone. Treated as "nothing to do": no file, no
  # export lines, and a clean message rather than an empty prompt cycle.
  if [ "$CHOICE" = "4" ]; then
    echo "  Nothing written — using your environment as-is."
    echo "  Run: ai-stack start"
    exit 0
  fi

  case "$CHOICE" in
    2|3)
      # Deliberately the STACK dir, not $PWD. Docker Compose only auto-loads
      # .env from the directory holding the compose file, so a .env written into
      # the user's project would be silently ignored.
      ENV_FILE="$DIR/.env"
      echo "# perfect-ai-stack" > "$ENV_FILE"
      echo "# Generated by: ai-stack wizard" >> "$ENV_FILE"
      echo "" >> "$ENV_FILE"
      ;;
  esac

  prompt_var() {
    local name="$1" desc="$2" default="${3:-}"
    local val
    val="$(eval echo \$$name 2>/dev/null || true)"
    if [ -n "$val" ]; then
      # Already exported in your shell — docker compose reads it from there, so
      # copying it into .env would only create a second copy to keep in sync.
      echo "  $name is set (environment)"
      return 0
    fi

    if [ -n "$default" ]; then
      printf "  %s (%s) [%s]: " "$name" "$desc" "$default"
    else
      printf "  %s (%s): " "$name" "$desc"
    fi
    read -r INPUT
    INPUT="${INPUT:-$default}"
    if [ -z "$INPUT" ] && [ -z "$default" ]; then
      echo "    Skipped"
      case "$CHOICE" in
        2|3)
          echo "# $name=" >> "$ENV_FILE"
          ;;
      esac
      return 0
    fi

    case "$CHOICE" in
      1|3)
        echo ""
        echo "  Run this in your terminal:"
        echo "    export $name=\"$INPUT\""
        echo ""
        ;;
    esac
    case "$CHOICE" in
      2|3)
        echo "$name=\"$INPUT\"" >> "$ENV_FILE"
        echo "  Saved to .env"
        ;;
    esac
  }

  prompt_var "ANTHROPIC_API_KEY" "Only if using Claude (chat model)" ""
  prompt_var "DEEPSEEK_API_KEY" "Only if using DeepSeek (chat model)" "$OPENAI_API_KEY"

  echo ""
  if [ "$CHOICE" != "1" ]; then
    echo "  Done! .env written to $ENV_FILE"
  else
    echo "  Done!"
  fi
}

check_deps() {
  if ! command -v docker >/dev/null 2>&1; then
    echo ""
    echo "  Docker isn't installed (or isn't on your PATH)."
    echo ""
    echo "  The gateway (LiteLLM + Headroom + Lore) runs in Docker."
    echo "  Install Docker Desktop:  https://docs.docker.com/get-docker/"
    echo ""
    echo "  Already have it open? Make sure the app is running, then retry."
    echo ""
    echo "  Don't want Docker at all? Run Lore natively instead:"
    echo "    npm i -g @loreai/gateway && lore start"
    echo "  (no Headroom compression; same http://localhost:3207/v1 endpoint)"
    echo ""
    exit 1
  fi
  # `docker volume`/`compose` need the daemon up; a stopped Docker Desktop is
  # the most common newbie failure and gives a confusing error deeper in.
  if ! docker info >/dev/null 2>&1; then
    echo ""
    echo "  Docker is installed but the daemon isn't responding."
    echo "  Start Docker Desktop and wait for it to finish booting, then retry."
    echo ""
    exit 1
  fi
}

# Install a GitHub Actions workflow that runs `lat check` on push/PR.
#
# Complements the pre-commit hook: the hook is local and bypassable
# (`--no-verify`), and never runs on pull requests. `lat check` is the same
# command in both places, so CI failures here are exactly what a committer
# would have seen locally.
#
# Skips silently when the target is not a GitHub repo, or when a workflow
# mentioning `lat check` already exists (so a user's own tuned workflow is
# never clobbered).
install_lat_workflow() {
  local target="$1"
  [ -d "$target/.git" ] || return 0

  # GitHub only? A remote pointing anywhere else means this file is dead weight.
  if ! git -C "$target" remote -v 2>/dev/null | grep -q 'github\.com'; then
    return 0
  fi

  local dir="$target/.github/workflows"
  local file="$dir/lat.yml"

  if [ -f "$file" ]; then
    return 0
  fi
  # Any existing workflow that already validates lat — leave it alone.
  if [ -d "$dir" ] && grep -rqsl 'lat check' "$dir" 2>/dev/null; then
    echo "  lat CI: existing workflow already runs 'lat check'"
    return 0
  fi

  mkdir -p "$dir" || return 0
  cat > "$file" <<'YAML'
# Validates the lat.md knowledge graph on every push and PR.
#
# The local pre-commit hook only guards `git commit`; it can be skipped with
# --no-verify and does not run for PRs from forks. This is the enforcement
# that cannot be bypassed.
name: lat

on:
  push:
    branches: [main, master]
  pull_request:

permissions:
  contents: read

jobs:
  check:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      # Pinned loosely on purpose: `lat check` is the contract, and the graph
      # format is stable across 0.x. Re-run this workflow after a major bump if
      # validation output changes shape.
      - uses: actions/setup-node@v4
        with:
          node-version: '24'
      - run: npm install -g lat.md
      - run: lat check
YAML
  echo "  lat CI: added .github/workflows/lat.yml"
}

# Install the git pre-commit hook that runs `lat check` on every commit in
# the given project. Idempotent: creates .git/hooks/pre-commit if missing,
# appends `lat check` to an existing hook that lacks it, skips if already
# present. Skipped (with a notice) when the target is not a git repository.
#
# The hook is only installed when `lat.md/` exists AND `lat` is runnable:
# `lat check` exits non-zero without a graph, so installing it into a project
# that was never initialized would block every commit. Callers run this AFTER
# scaffolding so the graph is usually present.
install_lat_hook() {
  local target="$1"
  if [ ! -d "$target/.git" ]; then
    echo "  (not a git repository — skipping pre-commit hook)"
    return 0
  fi
  if [ ! -d "$target/lat.md" ]; then
    echo "  (no lat.md/ yet — skipping pre-commit hook, re-run setup-lat after lat init)"
    return 0
  fi
  if ! command -v lat >/dev/null 2>&1; then
    echo "  (lat not on PATH — skipping pre-commit hook)"
    return 0
  fi
  local hook="$target/.git/hooks/pre-commit"
  if [ ! -f "$hook" ]; then
    mkdir -p "$(dirname "$hook")"
    cp "$DIR/scripts/pre-commit-hook.sh" "$hook"
    chmod +x "$hook"
    echo "  pre-commit hook installed (.git/hooks/pre-commit)"
  elif ! grep -q "lat check" "$hook" 2>/dev/null; then
    printf '\n# lat.md validation\n' >> "$hook"
    printf 'exec lat check 2>&1\n' >> "$hook"
    echo "  pre-commit hook updated (appended lat check)"
  else
    echo "  pre-commit hook already runs lat check"
  fi
}

# Scaffold + start in one step, for a project that has nothing set up yet.
# Meant to be run from the project you want to use, and safe to re-run.
#
# Idempotent and fast on re-runs: if the gateway is already healthy we skip
# `docker compose up` entirely, so pointing a second project at the stack does
# not bounce the containers a first project is mid-session in.
#
# Flow: start gateway -> pick models -> scaffold lat.md -> print IDE config.
# Model choice comes before scaffolding so the written .lore.json is in place
# before any session can run with the wrong worker.
#
# Non-interactive runs (npx in a script, CI) skip the prompts and write the
# defaults, so `init` never hangs waiting for input.
init() {
  local target="$PWD"
  echo "┌─────────────────────────────────────────────┐"
  echo "│  perfect-ai-stack — project init             │"
  echo "└─────────────────────────────────────────────┘"
  echo ""
  echo "Project: $target"
  echo ""

  if gateway_is_up; then
    echo "  Gateway already running — skipping startup."
  else
    check_deps
    # Capture the project dir BEFORE cd-ing to the stack dir: start_stack reads
    # $PWD to set AI_STACK_PROJECT_DIR, which becomes the :/app mount. Without
    # this, the cd below wins and the stack dir mounts instead — so Lore finds
    # no .lore.json, falls back to its hardcoded anthropic/claude-sonnet-4-6
    # worker model, and every worker call 400s. `start` exports it the same way.
    export AI_STACK_PROJECT_DIR="${AI_STACK_PROJECT_DIR:-$target}"
    # The gateway is shared across projects: start it from the stack dir (docker
    # compose only reads .env and the compose file from there), then scaffold
    # the caller's project. init() writes no file into the stack dir — the one
    # exception in this script is the wizard's .env, which must live there to be
    # read at all.
    ( cd "$DIR" && start_stack )
  fi

  choose_models "$target"
  setup_lat "$target"
  print_client_config
}

# Pick the session + worker models during onboarding, and set the curator
# default. Writes .lore.json (merging, so a re-run keeps other keys).
#
# Non-interactive: keep whatever .lore.json already says, else write defaults.
#
# The defaults are only written if they are actually usable. On a fresh machine
# Ollama may not be running or qwen3:8b may not be pulled, and writing a worker
# that cannot answer would fail later in the background where it is invisible.
# Fall back to any local model, and to the session model only as a last resort.
choose_models() {
  local target="$1"
  local cfg="$target/.lore.json"

  if [ ! -t 0 ]; then
    if [ -f "$cfg" ]; then
      echo "  Models: keeping existing .lore.json"
      show_model_state "$cfg"
      return 0
    fi

    local session worker
    if model_is_available "qwen3:8b" && model_is_local "qwen3:8b"; then
      session="qwen3:8b"; worker="qwen3:8b"
    else
      # Prefer any local model; qwen3:8b is only the shipped favourite.
      worker="$(available_models | awk -F'\t' '$2=="local" {print $1; exit}')"
      session="$worker"
    fi

    if [ -z "$worker" ]; then
      echo "  Models: none available yet — no .lore.json written."
      echo "  Start Ollama and pull a model, then re-run:  ollama pull qwen3:8b"
      return 0
    fi
    echo "  Models: defaults ($session session + worker, curator off)"
    write_model_choice "$target" "$session" "$worker"
    return 0
  fi

  echo "  Models — press Enter to accept the defaults."
  echo "  Defaults are the measured-best local pair and cost nothing to run."
  echo ""
  models "" ""
}

# Is the gateway already serving? Cheap enough to call before every start.
gateway_is_up() {
  curl -sf -o /dev/null --max-time 3 http://localhost:3207/v1/models 2>/dev/null
}

# Models this project can actually use: served by the gateway (so LiteLLM
# knows the provider, key and pricing) AND, for Ollama-backed models, pulled.
# A model that is in config/litellm.yaml but not pulled registers fine and then
# fails at request time with a confusing "model not found" — so it is not
# "available", and must not be offered as a choice.
#
# Prints `name<TAB>local|remote`. Anything Ollama has a tag for is local; the
# rest are remote providers reached through LiteLLM.
available_models() {
  local served pulled
  served="$(curl -sf --max-time 5 http://localhost:3207/v1/models 2>/dev/null \
    | tr ',' '\n' | sed -n 's/.*"id":"\([^"]*\)".*/\1/p' || true)"
  pulled="$(curl -sf --max-time 5 http://localhost:11434/api/tags 2>/dev/null \
    | tr ',' '\n' | sed -n 's/.*"name":"\([^"]*\)".*/\1/p' || true)"
  [ -n "$served" ] || return 0

  # Any served name that is not pulled is unusable UNLESS it is a remote model.
  # Remote models never appear in the Ollama list, and local names always carry
  # a tag, so a served name matching no pulled tag AND containing ':' is a
  # local tag that is missing; without ':' it is a remote model.
  local m
  printf '%s\n' "$served" | while IFS= read -r m; do
    [ -n "$m" ] || continue
    if printf '%s\n' "$pulled" | grep -qxF "$m"; then
      printf '%s\tlocal\n' "$m"
    elif printf '%s\n' "$m" | grep -q ':'; then
      : # local-style tag, not pulled -> unusable, skip
    else
      printf '%s\tremote\n' "$m"
    fi
  done
}

# Is this exact model usable right now?
model_is_available() {
  available_models | cut -f1 | grep -qxF "$1"
}

# Protocol a model speaks, derived from its LiteLLM provider entry. Anything
# on Ollama or DeepSeek speaks OpenAI; Anthropic entries speak the Messages
# API. Workers MUST match the session's protocol — cross-protocol calls fail
# (wrong credentials, wrong API format). Defaults to "openai" when unknown,
# which is correct for every model this stack ships.
model_protocol() {
  local m="$1"
  case "$m" in
    claude*|anthropic*) printf 'anthropic' ;;
    *) printf 'openai' ;;
  esac
}

# Advisory note shown next to a model. Purely informational: it never filters
# the list, because thinking mode is not a reliable quality proxy. Measured on
# the curation eval, the thinking `qwen3:8b` classified facts correctly while
# the non-thinking `ministral-3:8b` did not — so excluding thinking models
# would have removed the better worker.
#
# Name-based heuristic on purpose: neither /v1/models nor Ollama's tags expose
# a reasoning capability flag. Being wrong here only mislabels a hint.
model_notes() {
  local m="$1"
  case "$m" in
    qwen3*|*qwq*|*deepseek-r1*|*reasoner*) printf 'thinking: more tokens per call' ;;
    *) printf '' ;;
  esac
}

# Show + set the model selection for THIS project.
#
# Usage:
#   ai-stack models                       # show current selection + what's available
#   ai-stack models <session> [worker]    # set them
#   ai-stack models --curator on|off      # toggle curation
#   ai-stack models --reset               # back to the defaults
#
# Selection is per-project, stored in .lore.json (Lore reads model/workerModel
# from there), so switching needs no gateway restart and does not affect other
# projects. LORE_WORKER_MODEL stays the global env fallback.
models() {
  local target="$PWD"
  local cfg="$target/.lore.json"

  # `--yes` skips the remote-worker confirmation, for scripted use.
  local yes=""
  if [ "${1:-}" = "--yes" ] || [ "${1:-}" = "-y" ]; then
    yes="1"
    shift
  fi

  case "${1:-}" in
    --reset)
      write_model_choice "$target" "qwen3:8b" "qwen3:8b"
      return 0
      ;;
    --curator)
      set_curator "$target" "${2:-}"
      return 0
      ;;
    --help|-h)
      show_models_help
      return 0
      ;;
  esac

  # No arguments: show the current state, then offer to change it.
  if [ -z "${1:-}" ]; then
    show_model_state "$cfg"
    if [ ! -t 0 ]; then
      echo "  To change them:"
      echo "    ai-stack models <session-model> [worker-model]"
      echo "    ai-stack models --curator on|off"
      echo "    ai-stack models --reset"
      return 0
    fi
    echo ""
    printf "  Change them now? [y/N]: "
    read -r go
    case "$go" in [Yy]*) ;; *) return 0 ;; esac
  fi

  local choices
  choices="$(available_models)"
  if [ -z "$choices" ]; then
    echo ""
    echo "  No models available — is the gateway running? ('ai-stack start')"
    return 1
  fi
  echo ""
  echo "  Available models (served by the gateway AND usable now):"
  local n b note
  printf '%s\n' "$choices" | while IFS="$(printf '\t')" read -r n b; do
    [ -n "$n" ] || continue
    note="$(model_notes "$n")"
    printf '    %-24s %-7s %s\n' "$n" "$b" "$note"
  done
  echo ""
  echo "  'thinking' is a hint, not a restriction: it costs extra tokens per call,"
  echo "  which is local and free here. Prefer it when quality matters."
  echo ""

  # Non-interactive: `ai-stack models <session> <worker>` sets directly, but
  # only after validating both against the available list. Writing a name that
  # is not served turns into "Invalid model name" at request time, which reads
  # as a broken stack rather than a typo.
  if [ -n "${1:-}" ]; then
    local want_s="$1" want_w="${2:-}"
    if ! model_is_available "$want_s"; then
      echo "  '$want_s' is not available. Pick one of:"
      avail_names | sed 's/^/    /'
      return 1
    fi
    if [ -n "$want_w" ] && ! model_is_available "$want_w"; then
      echo "  '$want_w' is not available. Pick one of:"
      avail_names | sed 's/^/    /'
      return 1
    fi
    check_same_protocol "$want_s" "${want_w:-$want_s}" || return 1
    confirm_remote_worker "$want_w" "$yes" || return 1
    write_model_choice "$target" "$want_s" "$want_w"
    echo ""
    show_model_state "$cfg"
    return 0
  fi

  if [ ! -t 0 ]; then
    echo "  To set models non-interactively:"
    echo "    ai-stack models <session-model> [worker-model]"
    return 0
  fi

  local cur_s cur_w
  cur_s="$(read_model_field "$cfg" model)"
  cur_w="$(read_model_field "$cfg" workerModel)"
  # Defaults must be offerable AND safe. The worker default must never be a
  # remote model: pressing Enter on a remote worker would silently start
  # metering, which is the whole thing the confirmation step exists to prevent.
  # Prefer the current value, then the shipped local default, then any LOCAL
  # model, and only fall back to whatever exists if there is no local at all.
  [ -n "$cur_s" ] || cur_s="$(avail_names | head -1)"
  if [ -z "$cur_w" ] || ! model_is_local "$cur_w"; then
    if model_is_available "qwen3:8b" && model_is_local "qwen3:8b"; then
      cur_w="qwen3:8b"
    else
      cur_w="$(available_models | awk -F'\t' '$2=="local" {print $1; exit}')"
      [ -n "$cur_w" ] || cur_w="$cur_s"
    fi
  fi

  local session worker
  prompt_available_model "  Session model" "$cur_s" "any" && session="$REPLY" || return 1
  echo "  Worker runs on every session (distillation/curation). Keep it LOCAL and"
  echo "  free: qwen3:8b is the measured-best local model (scripts/eval-worker.sh)."
  prompt_available_model "  Worker model " "$cur_w" "local" && worker="$REPLY" || return 1

  check_same_protocol "$session" "$worker" || return 1
  confirm_remote_worker "$worker" "" || return 1
  write_model_choice "$target" "$session" "$worker"
  echo ""
  show_model_state "$cfg"
}

# Is this model local (Ollama on this machine) or remote (a cloud provider)?
model_is_local() {
  available_models | awk -F'\t' -v m="$1" '$1 == m && $2 == "local" { found=1 } END { exit !found }'
}

# Warn hard when a REMOTE model is chosen as the worker.
#
# The worker runs on every session (distillation, curation, query expansion)
# whether or not you chat, so a remote worker bills continuously — it is the
# single easiest way to turn a free local stack into a metered one by accident.
# $2 non-empty means --yes was passed (scripted), which proceeds.
confirm_remote_worker() {
  local w="$1" skip="$2"
  [ -n "$w" ] || return 0
  model_is_local "$w" && return 0

  echo ""
  echo "  ⚠ '$w' is a REMOTE model and you have chosen it as the WORKER."
  echo ""
  echo "    The worker runs on EVERY session — distillation, curation and query"
  echo "    expansion — whether or not you actually chat. A remote worker bills"
  echo "    continuously, so this turns a free local stack into a metered one."
  echo ""
  echo "    Remote is the right choice when your local model cannot curate well:"
  echo "    Lore's floor is 32B+ for reliable curation, and a cheap cloud model"
  echo "    (Haiku-class) is often better than a small local one."
  echo "    Otherwise pick a local worker — see 'ai-stack models' for the list."
  echo ""

  [ -n "$skip" ] && return 0
  if [ ! -t 0 ]; then
    echo "  Refusing in a non-interactive shell (a remote worker should be a"
    echo "  deliberate choice). To accept it, put --yes first:"
    echo "    ai-stack models --yes <session-model> $w"
    return 1
  fi
  printf "  Use a remote worker anyway? [y/N]: "
  local go
  read -r go
  case "$go" in
    [Yy]*) return 0 ;;
    *) echo "  Cancelled — nothing changed."; return 1 ;;
  esac
}

# Just the names, one per line.
avail_names() {
  available_models | cut -f1
}

# Prompt until the answer is an available model. Empty keeps the default.
#
# On a terminal with arrow-key support this is a menu: up/down to move, Enter to
# choose, q to cancel. `local_only` = "local" restricts the menu to local models
# (used for the worker, where a remote pick meters every session).
#
# On a plain pipe or a terminal without the needed escape handling, falls back
# to typed input — the previous behaviour — so scripted use still works.
# Sets REPLY. Returns 1 on cancel or too many invalid attempts.
prompt_available_model() {
  local label="$1" default="$2" filter="${3:-any}"

  local options
  options="$(available_models | while IFS="$(printf '\t')" read -r n b; do
    [ -n "$n" ] || continue
    if [ "$filter" = "local" ] && [ "$b" != "local" ]; then continue; fi
    printf '%s\t%s\n' "$n" "$b"
  done)"

  # A local-only prompt with no local models means Ollama is unreachable or
  # nothing is pulled. Refuse rather than quietly falling through to the remote
  # entries, which would hand the user a metered worker at the moment the
  # protection matters most.
  if [ "$filter" = "local" ] && [ -z "$options" ]; then
    echo ""
    echo "  No LOCAL models are available, so no worker can be chosen."
    echo "  The worker runs on every session, so it is deliberately not defaulted"
    echo "  to a remote model."
    echo ""
    echo "  Fix one of:"
    echo "    - start Ollama:      ollama serve"
    echo "    - pull a model:      ollama pull qwen3:8b"
    echo "    - allow a remote worker on purpose: ai-stack models --yes <session> <remote>"
    return 1
  fi

  # Menu only when we can read single keys. `read -rsn1` needs bash; this script
  # is run by sh, so probe for bash explicitly and fall back if absent.
  if [ -t 0 ] && [ -t 1 ] && command -v bash >/dev/null 2>&1; then
    select_model_menu "$label" "$default" "$options" && return 0
  fi

  # Fallback: typed entry.
  local answer tries=0
  while [ "$tries" -lt 5 ]; do
    printf "%s [%s]: " "$label" "$default"
    read -r answer
    answer="${answer:-$default}"
    if model_is_available "$answer"; then
      if [ "$filter" = "local" ] && ! model_is_local "$answer"; then
        echo "    '$answer' is remote; the worker must be local here."
        tries=$((tries + 1))
        continue
      fi
      REPLY="$answer"
      return 0
    fi
    echo "    '$answer' is not available. Choose from the list above (or add it"
    echo "    to config/litellm.yaml and run 'ai-stack restart')."
    tries=$((tries + 1))
  done
  echo "  Too many invalid attempts — nothing changed."
  return 1
}

# Arrow-key menu. Runs bash (scripts/select-model) because reading a single
# keypress needs `read -rsn1`, and this script is POSIX sh.
# Sets REPLY. Returns 1 if cancelled.
#
# The model list is piped on STDIN rather than passed as argv: names contain
# colons and the kind is tab-separated, and unquoted word-splitting on a tab
# would split each pair into two argv entries and pair them wrong.
select_model_menu() {
  local label="$1" default="$2" options="$3"
  local pick

  # List on fd 3; stdin stays free for the terminal's keypresses.
  pick="$(bash "$DIR/scripts/select-model" "$label" "$default" 3<<EOF
$options
EOF
)" || {
    echo "  Cancelled — nothing changed."
    return 1
  }
  [ -n "$pick" ] || { echo "  Cancelled — nothing changed."; return 1; }
  REPLY="$pick"
  return 0
}

# Refuse a session/worker pair that speaks different protocols. Lore's docs:
# "cross-provider calls always fail (wrong credentials, wrong API format)".
# Better to block it here than fail asynchronously in a background worker.
check_same_protocol() {
  local s p_s w p_w
  s="$1"; w="$2"
  p_s="$(model_protocol "$s")"
  p_w="$(model_protocol "$w")"
  if [ "$p_s" != "$p_w" ]; then
    echo ""
    echo "  Refusing: session ($s -> $p_s) and worker ($w -> $p_w) use different"
    echo "  APIs. Lore's workers must match the session's protocol — a mixed pair"
    echo "  fails at runtime with wrong credentials / wrong API format."
    echo "  Pick two models on the same API (both OpenAI-compatible here)."
    return 1
  fi
  return 0
}

