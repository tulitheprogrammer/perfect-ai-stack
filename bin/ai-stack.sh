#!/usr/bin/env bash
set -euo pipefail

# ai-stack — Docker-based AI proxy stack
# LiteLLM (+ Headroom compression) + Lore run in Docker; lat.md knowledge
# graph scaffolded per-repo with a git pre-commit hook for doc enforcement.

# Resolve $0 through symlinks: npx/npm invoke the bin via a symlink in
# node_modules/.bin, so dirname"$0" would be that .bin dir and ".." would
# land in node_modules (no docker-compose.yml there). Follow the chain to the
# real script inside the package, then the stack root is one level up.
SCRIPT="$0"
while [ -L "$SCRIPT" ]; do
  TARGET="$(readlink "$SCRIPT")"
  case "$TARGET" in
    /*) SCRIPT="$TARGET" ;;
    *)  SCRIPT="$(cd "$(dirname "$SCRIPT")" && pwd)/$TARGET" ;;
  esac
done
DIR="$(cd "$(dirname "$SCRIPT")/.." && pwd)"
CMD="${1:-help}"

wizard() {
  # `read`/`read -n1` fail on non-TTY stdin (EOF), and under `set -e` that
  # kills the wizard silently mid-flow. Fail loudly instead.
  if [ ! -t 0 ]; then
    echo "  The wizard is interactive — run it in a terminal."
    exit 1
  fi
  # .env is written to the directory you're running from ($PWD), so a
  # project-root invocation seeds that project's .env. The stack's docker
  # compose only auto-loads .env from the stack dir itself — running the
  # stack still happens there (ai-stack start) regardless.
  if [ "$PWD" != "$DIR" ]; then
    echo "  Note: .env will be written to the current project:"
    echo "    $PWD"
    echo "  The stack itself is at $DIR — run 'ai-stack start' there."
    echo "  (docker compose automatically loads .env only from its own dir.)"
    echo ""
  fi
  echo "┌─────────────────────────────────────────────┐"
  echo "│  perfect-ai-stack — Setup Wizard             │"
  echo "└─────────────────────────────────────────────┘"
  echo ""

  MISSING=""

  check_var() {
    local name="$1" desc="$2" default="${3:-}"
    local val
    val="$(eval echo \$$name 2>/dev/null || true)"
    if [ -z "$val" ]; then
      echo "  $name is not set"
      echo "    -> $desc"
      [ -n "$default" ] && echo "    (default: $default)"
      MISSING="$MISSING $name"
      return 1
    else
      echo "  $name is set"
      return 0
    fi
  }

  # `|| true` on purpose: check_var returns 1 for an unset var, and under
  # `set -e` a bare call would exit the wizard before showing the menu.
  check_var "ANTHROPIC_API_KEY" "Only if using Claude (chat model)" || true
  check_var "OPENAI_API_KEY" "Only if using DeepSeek/GPT-4o" || true

  echo ""
  if [ -z "$MISSING" ]; then
    echo "  All set. Run: ai-stack start"
    echo "  (No .env written — keys are already in your environment.)"
    exit 0
  fi

  echo "  Missing some vars. Pick how to provide them:"
  echo ""
  echo "  1) Print export commands (copy-paste into terminal)"
  echo "  2) Save to .env file (this project, auto-loaded by docker compose)"
  echo "  3) Both"
  echo ""
  # Single-keypress choice: reads one digit, no Enter required.
  printf "  Choose [1/2/3] (default: 1): "
  IFS= read -r -n1 CHOICE_KEY
  echo ""
  # Empty (Enter/EOF) -> default 1.
  CHOICE="${CHOICE_KEY:-1}"

  case "$CHOICE" in
    2|3)
      ENV_FILE="$PWD/.env"
      echo "# perfect-ai-stack" > "$ENV_FILE"
      echo "# Generated by: ai-stack wizard" >> "$ENV_FILE"
      echo "" >> "$ENV_FILE"
      ;;
  esac

  prompt_var() {
    local name="$1" desc="$2" default="${3:-}"
    local val
    val="$(eval echo \$$name 2>/dev/null || true)"
    if [ -n "$val" ]; then
      echo "  $name is set (environment)"
      case "$CHOICE" in
        2|3)
          echo "$name=\"$val\"" >> "$ENV_FILE"
          echo "  Saved to .env"
          ;;
      esac
      return 0
    fi

    if [ -n "$default" ]; then
      printf "  %s (%s) [%s]: " "$name" "$desc" "$default"
    else
      printf "  %s (%s): " "$name" "$desc"
    fi
    read -r INPUT
    INPUT="${INPUT:-$default}"
    if [ -z "$INPUT" ] && [ -z "$default" ]; then
      echo "    Skipped"
      case "$CHOICE" in
        2|3)
          echo "# $name=" >> "$ENV_FILE"
          ;;
      esac
      return 0
    fi

    case "$CHOICE" in
      1|3)
        echo ""
        echo "  Run this in your terminal:"
        echo "    export $name=\"$INPUT\""
        echo ""
        ;;
    esac
    case "$CHOICE" in
      2|3)
        echo "$name=\"$INPUT\"" >> "$ENV_FILE"
        echo "  Saved to .env"
        ;;
    esac
  }

  prompt_var "ANTHROPIC_API_KEY" "Only if using Claude (chat model)" ""
  prompt_var "OPENAI_API_KEY" "Only if using DeepSeek/GPT-4o" ""

  echo ""
  if [ "$CHOICE" != "1" ]; then
    echo "  Done! .env written to $PWD/.env"
  else
    echo "  Done!"
  fi
}

check_deps() {
  if ! command -v docker >/dev/null 2>&1; then
    echo ""
    echo "  Docker isn't installed (or isn't on your PATH)."
    echo ""
    echo "  The gateway (LiteLLM + Headroom + Lore) runs in Docker."
    echo "  Install Docker Desktop:  https://docs.docker.com/get-docker/"
    echo ""
    echo "  Already have it open? Make sure the app is running, then retry."
    echo ""
    echo "  Don't want Docker at all? Run Lore natively instead:"
    echo "    npm i -g @loreai/gateway && lore start"
    echo "  (no Headroom compression; same http://localhost:3207/v1 endpoint)"
    echo ""
    exit 1
  fi
  # `docker volume`/`compose` need the daemon up; a stopped Docker Desktop is
  # the most common newbie failure and gives a confusing error deeper in.
  if ! docker info >/dev/null 2>&1; then
    echo ""
    echo "  Docker is installed but the daemon isn't responding."
    echo "  Start Docker Desktop and wait for it to finish booting, then retry."
    echo ""
    exit 1
  fi
}

# Install the git pre-commit hook that runs `lat check` on every commit in
# the given project. Idempotent: creates .git/hooks/pre-commit if missing,
# appends `lat check` to an existing hook that lacks it, skips if already
# present. Skipped (with a notice) when the target is not a git repository.
#
# The hook is only installed when `lat.md/` exists AND `lat` is runnable:
# `lat check` exits non-zero without a graph, so installing it into a project
# that was never initialized would block every commit. Callers run this AFTER
# scaffolding so the graph is usually present.
install_lat_hook() {
  local target="$1"
  if [ ! -d "$target/.git" ]; then
    echo "  (not a git repository — skipping pre-commit hook)"
    return 0
  fi
  if [ ! -d "$target/lat.md" ]; then
    echo "  (no lat.md/ yet — skipping pre-commit hook, re-run setup-lat after lat init)"
    return 0
  fi
  if ! command -v lat >/dev/null 2>&1; then
    echo "  (lat not on PATH — skipping pre-commit hook)"
    return 0
  fi
  local hook="$target/.git/hooks/pre-commit"
  if [ ! -f "$hook" ]; then
    mkdir -p "$(dirname "$hook")"
    cp "$DIR/scripts/pre-commit-hook.sh" "$hook"
    chmod +x "$hook"
    echo "  pre-commit hook installed (.git/hooks/pre-commit)"
  elif ! grep -q "lat check" "$hook" 2>/dev/null; then
    printf '\n# lat.md validation\n' >> "$hook"
    printf 'exec lat check 2>&1\n' >> "$hook"
    echo "  pre-commit hook updated (appended lat check)"
  else
    echo "  pre-commit hook already runs lat check"
  fi
}

# Scaffold + start in one step, for a project that has nothing set up yet.
# Meant to be run from the project you want to use, and safe to re-run.
#
# Idempotent and fast on re-runs: if the gateway is already healthy we skip
# `docker compose up` entirely, so pointing a second project at the stack does
# not bounce the containers a first project is mid-session in.
#
# Flow: start gateway -> pick models -> scaffold lat.md -> print IDE config.
# Model choice comes before scaffolding so the written .lore.json is in place
# before any session can run with the wrong worker.
#
# Non-interactive runs (npx in a script, CI) skip the prompts and write the
# defaults, so `init` never hangs waiting for input.
init() {
  local target="$PWD"
  echo "┌─────────────────────────────────────────────┐"
  echo "│  perfect-ai-stack — project init             │"
  echo "└─────────────────────────────────────────────┘"
  echo ""
  echo "Project: $target"
  echo ""

  if gateway_is_up; then
    echo "  Gateway already running — skipping startup."
  else
    check_deps
    # The gateway is shared across projects: start it from the stack dir (docker
    # compose only reads .env and the compose file from there), then scaffold
    # the caller's project. Project files never land in the stack dir.
    ( cd "$DIR" && start_stack )
  fi

  choose_models "$target"
  setup_lat "$target"
  print_client_config
}

# Pick the session + worker models during onboarding, and set the curator
# default. Writes .lore.json (merging, so a re-run keeps other keys).
#
# Non-interactive: keep whatever .lore.json already says, else write defaults.
choose_models() {
  local target="$1"
  local cfg="$target/.lore.json"

  if [ ! -t 0 ]; then
    if [ -f "$cfg" ]; then
      echo "  Models: keeping existing .lore.json"
    else
      echo "  Models: defaults (qwen3:8b session + worker, curator off)"
      write_model_choice "$target" "qwen3:8b" "qwen3:8b"
    fi
    return 0
  fi

  echo "  Models — press Enter to accept the defaults."
  echo "  Defaults are the measured-best local pair and cost nothing to run."
  echo ""
  models "" ""
}

# Is the gateway already serving? Cheap enough to call before every start.
gateway_is_up() {
  curl -sf -o /dev/null --max-time 3 http://localhost:3207/v1/models 2>/dev/null
}

# List the models available to pick as session/worker.
available_models() {
  curl -sf --max-time 5 http://localhost:3207/v1/models 2>/dev/null \
    | tr ',' '\n' | sed -n 's/.*"id":"\([^"]*\)".*/\1/p'
}

# Show + set the model selection for THIS project.
#
# Usage:
#   ai-stack models                       # show current selection + what's available
#   ai-stack models <session> [worker]    # set them
#   ai-stack models --curator on|off      # toggle curation
#   ai-stack models --reset               # back to the defaults
#
# Selection is per-project, stored in .lore.json (Lore reads model/workerModel
# from there), so switching needs no gateway restart and does not affect other
# projects. LORE_WORKER_MODEL stays the global env fallback.
models() {
  local target="$PWD"
  local cfg="$target/.lore.json"

  case "${1:-}" in
    --reset)
      write_model_choice "$target" "qwen3:8b" "qwen3:8b"
      return 0
      ;;
    --curator)
      set_curator "$target" "${2:-}"
      return 0
      ;;
    --help|-h)
      show_models_help
      return 0
      ;;
  esac

  # No arguments: show the current state, then offer to change it.
  if [ -z "${1:-}" ]; then
    show_model_state "$cfg"
    if [ ! -t 0 ]; then
      echo "  To change them:"
      echo "    ai-stack models <session-model> [worker-model]"
      echo "    ai-stack models --curator on|off"
      echo "    ai-stack models --reset"
      return 0
    fi
    echo ""
    printf "  Change them now? [y/N]: "
    read -r go
    case "$go" in [Yy]*) ;; *) return 0 ;; esac
  fi

  echo ""
  echo "Available models (served by the gateway):"
  local names
  names="$(available_models)"
  if [ -z "$names" ]; then
    echo "  (gateway not reachable — run 'ai-stack start' first)"
    return 1
  fi
  echo "$names" | sed 's/^/  - /'
  echo ""

  # Non-interactive: `ai-stack models <session> <worker>` sets directly.
  if [ -n "${1:-}" ]; then
    write_model_choice "$target" "${1}" "${2:-}"
    echo ""
    show_model_state "$cfg"
    return 0
  fi
  if [ ! -t 0 ]; then
    echo "  To set models non-interactively:"
    echo "    ai-stack models <session-model> [worker-model]"
    return 0
  fi

  local cur_s cur_w
  cur_s="$(read_model_field "$cfg" model)"
  cur_w="$(read_model_field "$cfg" workerModel)"
  printf "  Session model [%s]: " "${cur_s:-qwen3:8b}"
  read -r session
  session="${session:-${cur_s:-qwen3:8b}}"
  echo "  Worker runs on every session (distillation/curation) — keep it LOCAL and"
  echo "  free. qwen3:8b is the measured-best local model (see scripts/eval-worker.sh)."
  printf "  Worker model  [%s]: " "${cur_w:-qwen3:8b}"
  read -r worker
  worker="${worker:-${cur_w:-qwen3:8b}}"
  write_model_choice "$target" "$session" "$worker"
  echo ""
  show_model_state "$cfg"
}

show_models_help() {
  cat <<'EOF'
  ai-stack models — choose the session and worker models for this project

    ai-stack models                        show current selection
    ai-stack models <session> [worker]     set them (e.g. qwen3:8b llama3.1:8b)
    ai-stack models --curator on           opt in to curation (.lore.md export)
    ai-stack models --curator off          opt out (the default)
    ai-stack models --reset                restore the defaults

  Stored in .lore.json at your project root, so it is per-project and needs no
  gateway restart. Re-run anytime; the environment default is unaffected.

  A model name must exist in config/litellm.yaml. To add a new one, append a
  model_list entry there and run `ai-stack restart` once.
EOF
}

# Print the effective selection, flagging anything that is not serving.
show_model_state() {
  local cfg="$1"
  local s w c
  s="$(read_model_field "$cfg" model)"
  w="$(read_model_field "$cfg" workerModel)"
  c="$(read_curator "$cfg")"
  echo "  Current selection ($cfg):"
  echo "    session: ${s:-qwen3:8b (env default)}"
  echo "    worker:  ${w:-$s (follows session)}"
  case "$c" in
    true)  echo "    curator: on   — writes .lore.md (needs a capable model)" ;;
    false) echo "    curator: off  — opt in with: ai-stack models --curator on" ;;
    *)     echo "    curator: off  — opt in with: ai-stack models --curator on" ;;
  esac

  # Warn when a chosen model is not currently served: the failure otherwise
  # only appears at request time as a confusing "Invalid model name".
  local avail
  avail="$(available_models)"
  if [ -n "$avail" ]; then
    local m
    for m in "$s" "$w"; do
      [ -n "$m" ] || continue
      if ! printf '%s\n' "$avail" | grep -qxF "$m"; then
        echo "    ! '$m' is not served by the gateway — add it to config/litellm.yaml"
        echo "      then run: ai-stack restart"
      fi
    done
  fi
}

# Read modelID from a .lore.json path (model or workerModel); empty if unset.
read_model_field() {
  local cfg="$1" key="$2"
  [ -f "$cfg" ] || return 0
  node -e '
    const fs = require("fs");
    try {
      const c = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
      process.stdout.write((c[process.argv[2]] || {}).modelID || "");
    } catch {}
  ' "$cfg" "$key" 2>/dev/null || true
}

read_curator() {
  local cfg="$1"
  [ -f "$cfg" ] || return 0
  node -e '
    const fs = require("fs");
    try {
      const c = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
      if (c.curator && typeof c.curator.enabled === "boolean") {
        process.stdout.write(String(c.curator.enabled));
      }
    } catch {}
  ' "$cfg" 2>/dev/null || true
}

# Toggle curation (the .lore.md export). Off by default; opt-in is explicit.
set_curator() {
  local target="$1" want="${2:-}"
  local cfg="$target/.lore.json"
  case "$want" in
    on|true|enable|enabled)
      node -e '
        const fs = require("fs");
        const [p] = process.argv.slice(1);
        let c = {}; try { c = JSON.parse(fs.readFileSync(p, "utf8")); } catch {}
        c.curator = { enabled: true };
        fs.writeFileSync(p, JSON.stringify(c, null, 2) + "\n");
      ' "$cfg" || { echo "  failed to write $cfg"; return 1; }
      echo "  Curation ON — Lore will write .lore.md entries automatically."
      echo "  .lore.md is committed and PR-reviewed, so check what it records."
      echo "  Lore's floor is 32B+ for reliable curation; on an 8B worker expect"
      echo "  misclassified entries. Verify with: sh scripts/eval-worker.sh"
      ;;
    off|false|disable|disabled)
      node -e '
        const fs = require("fs");
        const [p] = process.argv.slice(1);
        let c = {}; try { c = JSON.parse(fs.readFileSync(p, "utf8")); } catch {}
        c.curator = { enabled: false };
        fs.writeFileSync(p, JSON.stringify(c, null, 2) + "\n");
      ' "$cfg" || { echo "  failed to write $cfg"; return 1; }
      echo "  Curation OFF — distillation, recall, context management and lat.md"
      echo "  indexing all keep working; .lore.md stops being written."
      ;;
    *)
      echo "  Usage: ai-stack models --curator on|off"
      return 1
      ;;
  esac
}

# Merge the two model choices into .lore.json without clobbering other keys.
# Uses node (already a dependency of this package's runtime) instead of jq,
# which is not installed by default on macOS.
write_model_choice() {
  local target="$1" session="$2" worker="$3"
  local cfg="$target/.lore.json"
  node -e '
    const fs = require("fs");
    const [path, session, worker] = process.argv.slice(1);
    let cfg = {};
    try { cfg = JSON.parse(fs.readFileSync(path, "utf8")); } catch {}
    // providerID/modelID: both are "openai" here because every model in this
    // stack is reached through LiteLLM over the OpenAI protocol.
    cfg.model = { providerID: "openai", modelID: session };
    if (worker) cfg.workerModel = { providerID: "openai", modelID: worker };
    // Curator off by default. Curation writes durable entries into .lore.md,
    // which is committed and PR-reviewed; an 8B local model misclassifies
    // them (measured), and lat.md already carries the architecture knowledge.
    // Only set it on first write so an explicit opt-in is never overridden.
    if (!cfg.curator) cfg.curator = { enabled: false };
    fs.writeFileSync(path, JSON.stringify(cfg, null, 2) + "\n");
  ' "$cfg" "$session" "$worker" || { echo "  failed to write $cfg"; return 1; }
  echo ""
  echo "  Wrote $cfg:"
  echo "    session: $session"
  [ -n "$worker" ] && echo "    worker:  $worker"
  echo "    curator: off (opt in with {\"curator\": {\"enabled\": true}})"
  echo ""
  echo "  Workers must use the same provider as the session, and any model name"
  echo "  must exist in config/litellm.yaml — edit that file to add more."
  echo "  Prefer a LOCAL worker model: it runs every session, so a cloud worker"
  echo "  bills on every session. See README \"Make the worker a local model\"."
}

# Start the gateway without exiting on an already-running stack.
start_stack() {
  export AI_STACK_PROJECT_DIR="${AI_STACK_PROJECT_DIR:-$PWD}"
  DATA_DIR="${AI_STACK_DATA_DIR:-$DIR/data}"
  mkdir -p "$DATA_DIR/lore" "$DATA_DIR/headroom"
  # Build only when the images don't exist yet: a rebuild is minutes, which is
  # too much to pay on every `init`. `ai-stack update` stays the explicit
  # rebuild path.
  #
  # The image prefix is the compose project name, which derives from the stack
  # directory name unless the compose file pins it — so don't hardcode it.
  # Ask compose for the images it knows about instead of guessing.
  if docker compose images -q 2>/dev/null | grep -q .; then
    echo "Starting the gateway..."
    docker compose up -d
  else
    echo "Building + starting the gateway (first run takes a few minutes)..."
    docker compose up -d --build
  fi
  wait_for_gateway
}

# `docker compose up -d` returns as soon as containers are *created*, not when
# LiteLLM is accepting requests. Without this wait, the first IDE request after
# init races the boot and fails with ECONNREFUSED/502 (Lore -> litellm:4000).
wait_for_gateway() {
  local i
  printf "  Waiting for the gateway to be ready"
  for i in $(seq 1 60); do
    if curl -sf -o /dev/null --max-time 3 http://localhost:3207/v1/models 2>/dev/null; then
      printf " — ready.\n"
      return 0
    fi
    printf "."
    sleep 2
  done
  printf "\n"
  echo "  Gateway didn't respond within 2 minutes. Check: ai-stack logs"
  return 1
}

# The one thing every new user needs and can't guess: what to put in their IDE.
print_client_config() {
  echo ""
  echo "  Point your IDE / coding agent at:"
  echo ""
  echo "    Base URL:  http://localhost:3207/v1"
  echo "    API key:   any non-empty string (auth is off on this local stack)"
  echo "    Model:     qwen3:8b        (free, local via Ollama)"
  echo "               deepseek-v4-flash   (needs OPENAI_API_KEY)"
  echo ""
  echo "  Verify it answers:  curl -s http://localhost:3207/v1/models"
  echo "  Memory dashboard:   http://localhost:3207/ui"
  echo "  Gateway logs:       ai-stack logs"
  echo ""
}

# this package serves every repo:
#   cd some/project && sh /path/to/perfect-ai-stack/bin/ai-stack.sh setup-lat
#
# `lat init` is interactive in the sense that it asks which coding agents to
# wire up, but it does NOT require a TTY: with no input it still creates a
# valid lat.md/ and prints "you can re-run lat init later". So it always runs
# (stdin redirected from /dev/null) — the earlier TTY-only guard meant npx and
# scripted runs left the project without a graph, and the pre-commit hook then
# failed `lat check` on every commit. Re-run interactively afterwards to pick
# agents/hooks/MCP.
# Pass "strict" as $2 to fail the command when `lat check` fails (used by the
# explicit setup-lat command).
setup_lat() {
  local target="${1:-$PWD}"
  local strict="${2:-}"

  # 1. Install lat if missing (single global copy, shared by all projects).
  #    Under npx the global prefix may be unwritable; don't die on that — the
  #    later steps degrade gracefully when `lat` is absent.
  if ! command -v lat >/dev/null 2>&1; then
    npm install -g lat.md || echo "  (could not install lat globally — install it manually: npm i -g lat.md)"
  fi

  # 2. Scaffold lat.md/ when missing, or still just the committed placeholder
  #    intro file (1 file, no sections).
  if [ ! -d "$target/lat.md" ] || [ "$(find "$target/lat.md" -type f 2>/dev/null | wc -l | tr -d ' ')" = "1" ]; then
    if command -v lat >/dev/null 2>&1; then
      (cd "$target" && lat init "$target" < /dev/null) \
        || echo "  lat.md not initialized — run 'lat init' in $target"
    else
      echo "  lat.md not initialized in $target — run 'npm i -g lat.md && lat init'"
    fi
  fi

  # 3. Git pre-commit hook — `lat check` blocks commits with doc drift
  install_lat_hook "$target"

  # 4. .gitignore hygiene
  local gitignore="$target/.gitignore"
  if [ -f "$gitignore" ]; then
    for entry in "lat.md/.cache/" "lat.md/node_modules/"; do
      if ! grep -qF "$entry" "$gitignore"; then
        printf '%s\n' "$entry" >> "$gitignore"
        echo "  .gitignore: added $entry"
      fi
    done
  else
    printf 'lat.md/.cache/\nlat.md/node_modules/\n' > "$gitignore"
    echo "  .gitignore: created with lat entries"
  fi

  # 5. Verify — soft during start (docs are a quality gate, not a runtime
  #    gate), strict on explicit `ai-stack setup-lat`.
  if (cd "$target" && lat check >/dev/null 2>&1); then
    echo "  lat check: OK"
  else
    echo "  lat check: FAILED — fix the graph, then re-run"
    if [ "$strict" = "strict" ]; then
      return 1
    fi
  fi
}

case "$CMD" in
  wizard|config)
    wizard
    ;;
  init|onboard)
    init
    ;;
  start|up)
    check_deps
    # Project dir: where .lore.md exports and default session attribution land.
    # Capture $PWD before cd-ing to the stack dir (defaults to the whole stack
    # dir when run from a clone, like old behavior). Exported so docker compose
    # interpolates it into the :/app mount.
    export AI_STACK_PROJECT_DIR="${AI_STACK_PROJECT_DIR:-$PWD}"
    PROJECT_DIR="$AI_STACK_PROJECT_DIR"
    cd "$DIR"
    start_stack
    setup_lat "$PROJECT_DIR"
