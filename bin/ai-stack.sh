# Print the effective selection, flagging anything that is not serving.
# Is this name declared in config/litellm.yaml, regardless of whether it is
# currently served? Distinguishes "you picked a name the config doesn't define"
# (edit the config) from "the config defines it but the gateway hasn't picked it
# up yet" (restart) from "the config never heard of it" (stale selection after a
# rename — point at `models` instead of sending the user to edit the config).
model_in_config() {
  local name="$1"
  [ -n "$name" ] || return 1
  [ -f "$DIR/config/litellm.yaml" ] || return 1
  grep -qE "^[[:space:]]*-[[:space:]]*model_name:[[:space:]]*['\"]?${name}['\"]?[[:space:]]*$" \
    "$DIR/config/litellm.yaml"
}

# Explain why a selected model can't be used, and what to do about it.
# The right advice depends on the cause, and the causes look identical in the
# logs — a wrong hint here sends the user to edit a file that is already correct.
why_unavailable() {
  local m="$1"
  if model_in_config "$m"; then
    echo "    ! '$m' is defined in config/litellm.yaml but the gateway is not"
    echo "      serving it — restart to pick up the config:"
    echo "        ai-stack restart"
  else
    echo "    ! '$m' is not in config/litellm.yaml (not served, or a local model"
    echo "      that is not pulled). If it was renamed, re-select with:"
    echo "        ai-stack models"
    echo "      To add a new model instead, append it to config/litellm.yaml and"
    echo "      run: ai-stack restart"
    echo "      Local models also need: ollama pull $m"
  fi
}

show_model_state() {
  local cfg="$1"
  local s w c
  s="$(read_model_field "$cfg" model)"
  w="$(read_model_field "$cfg" workerModel)"
  c="$(read_curator "$cfg")"
  echo "  Current selection ($cfg):"
  local note
  note="$(model_notes "$s")"
  echo "    session: ${s:-qwen3:8b (env default)}${note:+   ($note)}"
  note="$(model_notes "$w")"
  echo "    worker:  ${w:-$s (follows session)}${note:+   ($note)}"
  # Keep the cost of a remote worker visible after the fact: it bills on every
  # session, and nothing else in the output distinguishes it from a free one.
  if [ -n "$w" ] && ! model_is_local "$w"; then
    echo "    ! worker '$w' is REMOTE — it bills on every session, whether or not"
    echo "      you chat. For free local work: ai-stack models $s <local-model>"
  fi
  case "$c" in
    true)  echo "    curator: on   — writes .lore.md (needs a capable model)" ;;
    false) echo "    curator: off  — opt in with: ai-stack models --curator on" ;;
    *)     echo "    curator: off  — opt in with: ai-stack models --curator on" ;;
  esac

  # Warn when a chosen model is not usable right now: the failure otherwise
  # only appears at request time as a confusing "Invalid model name".
  local m
  for m in "$s" "$w"; do
    [ -n "$m" ] || continue
    if ! model_is_available "$m"; then
      why_unavailable "$m"
    fi
  done
}

# Read modelID from a .lore.json path (model or workerModel); empty if unset.
read_model_field() {
  local cfg="$1" key="$2"
  [ -f "$cfg" ] || return 0
  node -e '
    const fs = require("fs");
    try {
      const c = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
      process.stdout.write((c[process.argv[2]] || {}).modelID || "");
    } catch {}
  ' "$cfg" "$key" 2>/dev/null || true
}

read_curator() {
  local cfg="$1"
  [ -f "$cfg" ] || return 0
  node -e '
    const fs = require("fs");
    try {
      const c = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
      if (c.curator && typeof c.curator.enabled === "boolean") {
        process.stdout.write(String(c.curator.enabled));
      }
    } catch {}
  ' "$cfg" 2>/dev/null || true
}

# Toggle curation (the .lore.md export). Off by default; opt-in is explicit.
set_curator() {
  local target="$1" want="${2:-}"
  local cfg="$target/.lore.json"
  case "$want" in
    on|true|enable|enabled)
      node -e '
        const fs = require("fs");
        const [p] = process.argv.slice(1);
        let c = {}; try { c = JSON.parse(fs.readFileSync(p, "utf8")); } catch {}
        c.curator = { enabled: true };
        fs.writeFileSync(p, JSON.stringify(c, null, 2) + "\n");
      ' "$cfg" || { echo "  failed to write $cfg"; return 1; }
      echo "  Curation ON — Lore will write .lore.md entries automatically."
      echo "  .lore.md is committed and PR-reviewed, so check what it records."
      echo "  Lore's floor is 32B+ for reliable curation; on an 8B worker expect"
      echo "  misclassified entries. Verify with: sh scripts/eval-worker.sh"
      ;;
    off|false|disable|disabled)
      node -e '
        const fs = require("fs");
        const [p] = process.argv.slice(1);
        let c = {}; try { c = JSON.parse(fs.readFileSync(p, "utf8")); } catch {}
        c.curator = { enabled: false };
        fs.writeFileSync(p, JSON.stringify(c, null, 2) + "\n");
      ' "$cfg" || { echo "  failed to write $cfg"; return 1; }
      echo "  Curation OFF — distillation, recall, context management and lat.md"
      echo "  indexing all keep working; .lore.md stops being written."
      ;;
    *)
      echo "  Usage: ai-stack models --curator on|off"
      return 1
      ;;
  esac
}

# Merge the two model choices into .lore.json without clobbering other keys.
# Uses node (already a dependency of this package's runtime) instead of jq,
# which is not installed by default on macOS.
write_model_choice() {
  local target="$1" session="$2" worker="$3"
  local cfg="$target/.lore.json"
  node -e '
    const fs = require("fs");
    const [path, session, worker] = process.argv.slice(1);
    let cfg = {};
    try { cfg = JSON.parse(fs.readFileSync(path, "utf8")); } catch {}
    // providerID/modelID: both are "openai" here because every model in this
    // stack is reached through LiteLLM over the OpenAI protocol.
    cfg.model = { providerID: "openai", modelID: session };
    if (worker) cfg.workerModel = { providerID: "openai", modelID: worker };
    // Curator off by default. Curation writes durable entries into .lore.md,
    // which is committed and PR-reviewed; an 8B local model misclassifies
    // them (measured), and lat.md already carries the architecture knowledge.
    // Only set it on first write so an explicit opt-in is never overridden.
    if (!cfg.curator) cfg.curator = { enabled: false };
    fs.writeFileSync(path, JSON.stringify(cfg, null, 2) + "\n");
  ' "$cfg" "$session" "$worker" || { echo "  failed to write $cfg"; return 1; }
  echo ""
  echo "  Wrote $cfg:"
  echo "    session: $session"
  [ -n "$worker" ] && echo "    worker:  $worker"
  echo "    curator: off (opt in with {\"curator\": {\"enabled\": true}})"
  echo ""
  echo "  Workers must use the same provider as the session, and any model name"
  echo "  must exist in config/litellm.yaml — edit that file to add more."
  echo "  Prefer a LOCAL worker model: it runs every session, so a cloud worker"
  echo "  bills on every session. See README \"Make the worker a local model\"."
}

# Start the gateway without exiting on an already-running stack.
start_stack() {
  export AI_STACK_PROJECT_DIR="${AI_STACK_PROJECT_DIR:-$PWD}"
  DATA_DIR="${AI_STACK_DATA_DIR:-$DIR/data}"
  mkdir -p "$DATA_DIR/lore" "$DATA_DIR/headroom"
  # Build only when the images don't exist yet: a rebuild is minutes, which is
  # too much to pay on every `init`. `ai-stack update` stays the explicit
  # rebuild path.
  #
  # The image prefix is the compose project name, which derives from the stack
  # directory name unless the compose file pins it — so don't hardcode it.
  # Ask compose for the images it knows about instead of guessing.
  if docker compose images -q 2>/dev/null | grep -q .; then
    echo "Starting the gateway..."
    docker compose up -d
  else
    echo "Building + starting the gateway (first run takes a few minutes)..."
    docker compose up -d --build
  fi
  wait_for_gateway
}

# `docker compose up -d` returns as soon as containers are *created*, not when
# LiteLLM is accepting requests. Without this wait, the first IDE request after
# init races the boot and fails with ECONNREFUSED/502 (Lore -> litellm:4000).
wait_for_gateway() {
  local i
  printf "  Waiting for the gateway to be ready"
  for i in $(seq 1 60); do
    if curl -sf -o /dev/null --max-time 3 http://localhost:3207/v1/models 2>/dev/null; then
      printf " — ready.\n"
      return 0
    fi
    printf "."
    sleep 2
  done
  printf "\n"
  echo "  Gateway didn't respond within 2 minutes. Check: ai-stack logs"
  return 1
}

# The one thing every new user needs and can't guess: what to put in their IDE.
#
# Reports the ACTUAL selection from .lore.json rather than a static blurb — the
# IDE talks to the SESSION model only, so the worker is shown separately as
# context (it is never typed into an editor).
print_client_config() {
  local cfg="$PWD/.lore.json"
  local s w
  s="$(read_model_field "$cfg" model)"; [ -n "$s" ] || s="qwen3:8b"
  w="$(read_model_field "$cfg" workerModel)"

  echo ""
  echo "  Point your IDE / coding agent at:"
  echo ""
  echo "    Base URL:  http://localhost:3207/v1"
  echo "    API key:   any non-empty string (auth is off on this local stack)"
  echo "    Model:     $s"
  case "$s" in
    deepseek*) echo "               (remote — needs DEEPSEEK_API_KEY in your environment)" ;;
    *)         echo "               (local via Ollama)" ;;
  esac
  echo ""
  if [ -n "$w" ]; then
    echo "    Background worker (not typed into the IDE): $w"
    model_is_local "$w" || echo "      ! remote worker — bills on every session"
  fi
  echo "  Verify it answers:  curl -s http://localhost:3207/v1/models"
  echo "  Memory dashboard:   http://localhost:3207/ui"
  echo "  Gateway logs:       ai-stack logs"
  echo "  Change models:      ai-stack models"
  echo ""
}

# this package serves every repo:
#   cd some/project && sh /path/to/perfect-ai-stack/bin/ai-stack.sh setup-lat
#
# `lat init` is interactive in the sense that it asks which coding agents to
# wire up, but it does NOT require a TTY: with no input it still creates a
# valid lat.md/ and prints "you can re-run lat init later". So it always runs
# (stdin redirected from /dev/null) — the earlier TTY-only guard meant npx and
# scripted runs left the project without a graph, and the pre-commit hook then
# failed `lat check` on every commit. Re-run interactively afterwards to pick
# agents/hooks/MCP.
# Pass "strict" as $2 to fail the command when `lat check` fails (used by the
# explicit setup-lat command).
setup_lat() {
  local target="${1:-$PWD}"
  local strict="${2:-}"

  # 1. Install lat if missing (single global copy, shared by all projects).
  #    Under npx the global prefix may be unwritable; don't die on that — the
  #    later steps degrade gracefully when `lat` is absent.
  if ! command -v lat >/dev/null 2>&1; then
    npm install -g lat.md || echo "  (could not install lat globally — install it manually: npm i -g lat.md)"
  fi

  # 2. Scaffold lat.md/ when missing, or still just the committed placeholder
  #    intro file (1 file, no sections).
  if [ ! -d "$target/lat.md" ] || [ "$(find "$target/lat.md" -type f 2>/dev/null | wc -l | tr -d ' ')" = "1" ]; then
    if command -v lat >/dev/null 2>&1; then
      (cd "$target" && lat init "$target" < /dev/null) \
        || echo "  lat.md not initialized — run 'lat init' in $target"
    else
      echo "  lat.md not initialized in $target — run 'npm i -g lat.md && lat init'"
    fi
  fi

  # 3. Git pre-commit hook — `lat check` blocks commits with doc drift
  install_lat_hook "$target"

  # 4. .gitignore hygiene
  local gitignore="$target/.gitignore"
  if [ -f "$gitignore" ]; then
    for entry in "lat.md/.cache/" "lat.md/node_modules/"; do
      if ! grep -qF "$entry" "$gitignore"; then
        printf '%s\n' "$entry" >> "$gitignore"
        echo "  .gitignore: added $entry"
      fi
    done
  else
    printf 'lat.md/.cache/\nlat.md/node_modules/\n' > "$gitignore"
    echo "  .gitignore: created with lat entries"
  fi

  # 5. GitHub Actions workflow — enforces `lat check` in CI.
  #
  # The pre-commit hook only guards local `git commit`; it is bypassable with
  # `--no-verify` and never runs on PRs from forks. This closes that gap.
  #
  # Uses the CLI (`npm i -g lat.md`) rather than vercel-labs/lat.md@action-v1:
  # the published Action tags do not exist yet (`git/matching-refs/tags/action`
  # is empty), so a workflow referencing one fails immediately on a missing ref.
  # Upgrade path: once an action-vX.Y.Z tag is released, switch to
  # `uses: vercel-labs/lat.md@action-vX.Y.Z` and drop the Node/npm steps.
  #
  # Only written when the target is a git repo with a GitHub remote — dropping
  # .github/workflows/ into a non-GitHub project is noise. Never overwrites an
  # existing lat workflow.
  install_lat_workflow "$target"

  # 6. Verify — soft during start (docs are a quality gate, not a runtime
  #    gate), strict on explicit `ai-stack setup-lat`.
  if (cd "$target" && lat check >/dev/null 2>&1); then
    echo "  lat check: OK"
  else
    echo "  lat check: FAILED — fix the graph, then re-run"
    if [ "$strict" = "strict" ]; then
      return 1
    fi
  fi
}

case "$CMD" in
  wizard|config)
