#!/usr/bin/env bash
set -euo pipefail

# ai-stack — Docker-based AI proxy stack

DIR="$(cd "$(dirname "$0")/.." && pwd)"
CMD="${1:-help}"

wizard() {
  echo "┌─────────────────────────────────────────────┐"
  echo "│  perfect-ai-stack — Setup Wizard             │"
  echo "└─────────────────────────────────────────────┘"
  echo ""

  MISSING=""

  check_var() {
    local name="$1" desc="$2" default="${3:-}"
    local val
    val="$(eval echo \$$name 2>/dev/null || true)"
    if [ -z "$val" ]; then
      echo "  \xE2\x9C\x97 $name is not set"
      echo "    -> $desc"
      [ -n "$default" ] && echo "    (default: $default)"
      MISSING="$MISSING $name"
      return 1
    else
      echo "  \xE2\x9C\x93 $name is set"
      return 0
    fi
  }

  check_var "ANTHROPIC_API_KEY" "Required for Claude 3.5 Sonnet"
  check_var "OPENAI_API_KEY" "Required for GPT-4o"
  check_var "LITELLM_MASTER_KEY" "LiteLLM admin key" "sk-litellm-master"
  check_var "LORE_CHAT_MODEL" "Model for chat sessions" "claude-3-5-sonnet"
  check_var "LORE_WORKER_MODEL" "Model for background workers" "local-llama"

  echo ""
  if [ -z "$MISSING" ]; then
    echo "  All set. Run: ai-stack start"
    exit 0
  fi

  echo "  Missing some vars. Pick how to provide them:"
  echo ""
  echo "  1) Print export commands (copy-paste into terminal)"
  echo "  2) Save to .env file (auto-loaded by docker compose)"
  echo "  3) Both"
  echo ""
  printf "  Choose [1/2/3] (default: 1): "
  read -r CHOICE
  CHOICE="${CHOICE:-1}"

  case "$CHOICE" in
    2|3)
      ENV_FILE="$DIR/.env"
      echo "# perfect-ai-stack" > "$ENV_FILE"
      echo "# Generated by: ai-stack wizard" >> "$ENV_FILE"
      echo "" >> "$ENV_FILE"
      ;;
  esac

  prompt_var() {
    local name="$1" desc="$2" default="${3:-}"
    local val
    val="$(eval echo \$$name 2>/dev/null || true)"
    [ -n "$val" ] && return 0

    if [ -n "$default" ]; then
      printf "  %s (%s) [%s]: " "$name" "$desc" "$default"
    else
      printf "  %s (%s): " "$name" "$desc"
    fi
    read -r INPUT
    INPUT="${INPUT:-$default}"
    if [ -z "$INPUT" ] && [ -z "$default" ]; then
      echo "    Skipped"
      return 0
    fi

    case "$CHOICE" in
      1|3)
        echo ""
        echo "  Run this in your terminal:"
        echo "    export $name=\"$INPUT\""
        echo ""
        ;;
    esac
    case "$CHOICE" in
      2|3)
        echo "$name=\"$INPUT\"" >> "$ENV_FILE"
        echo "  Saved to .env"
        ;;
    esac
  }

  prompt_var "ANTHROPIC_API_KEY" "Required for Claude 3.5 Sonnet" ""
  prompt_var "OPENAI_API_KEY" "Required for GPT-4o" ""
  prompt_var "LITELLM_MASTER_KEY" "LiteLLM admin key" "sk-litellm-master"
  prompt_var "LORE_CHAT_MODEL" "Model for chat sessions" "claude-3-5-sonnet"
  prompt_var "LORE_WORKER_MODEL" "Model for background workers" "local-llama"

  echo ""
  echo "  Done!"
}

case "$CMD" in
  wizard|setup|config)
    wizard
    ;;
  start|up)
    echo "Starting AI stack..."
    cd "$DIR" && docker compose up -d
    echo "  Lore    -> http://localhost:3207"
    echo "  LiteLLM -> http://localhost:4000"
    ;;
  stop|down)
    echo "Stopping AI stack..."
    cd "$DIR" && docker compose down
    echo "Done"
    ;;
  restart)
    cd "$DIR" && docker compose restart
    echo "Done"
    ;;
  logs)
    cd "$DIR" && docker compose logs -f
    ;;
  ps|status)
    cd "$DIR" && docker compose ps
    ;;
  update)
    cd "$DIR" && docker compose pull && docker compose up -d
    echo "Done"
    ;;
  setup-lat)
    command -v lat >/dev/null 2>&1 || npm install -g lat.md
    [ -f "$PWD/lat.md/lat.md" ] || (cd "$PWD" && lat init)
    echo "lat.md ready"
    ;;
  help|*)
    echo "perfect-ai-stack -- Docker-based AI proxy stack"
    echo ""
    echo "Commands:"
    echo "  wizard     Interactive setup for env vars"
    echo "  start      Start containers"
    echo "  stop       Stop containers"
    echo "  restart    Restart containers"
    echo "  logs       Follow logs"
    echo "  ps         Container status"
    echo "  update     Pull latest images and recreate"
    echo "  setup-lat  Scaffold lat.md in current project"
    echo ""
    echo "Quick start:"
    echo "  ai-stack wizard"
    echo "  ai-stack start"
    ;;
esac
