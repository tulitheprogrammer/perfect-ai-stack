#!/usr/bin/env bash
set -euo pipefail

# ai-stack — Docker-based AI proxy stack
# LiteLLM (+ Headroom compression) + Lore run in Docker; lat.md knowledge
# graph scaffolded per-repo with a git pre-commit hook for doc enforcement.

DIR="$(cd "$(dirname "$0")/.." && pwd)"
CMD="${1:-help}"

wizard() {
  # `read` fails on non-TTY stdin (EOF), and under `set -e` that kills the
  # wizard silently mid-flow — after the header write, before any keys are
  # saved. Fail loudly instead.
  if [ ! -t 0 ]; then
    echo "  The wizard is interactive — run it in a terminal."
    exit 1
  fi
  # The wizard configures the SHARED stack; .env belongs next to docker
  # compose (in the stack dir), not in whichever directory you ran from.
  if [ "$PWD" != "$DIR" ]; then
    echo "  Note: this wizard configures the shared stack at:"
    echo "    $DIR"
    echo "  .env will be written there (docker compose reads it from the stack),"
    echo "  not in the current directory. For per-project scaffolding (lat.md"
    echo "  + hooks), use: ai-stack setup-lat"
    echo ""
  fi
  echo "┌─────────────────────────────────────────────┐"
  echo "│  perfect-ai-stack — Setup Wizard             │"
  echo "└─────────────────────────────────────────────┘"
  echo ""

  MISSING=""

  check_var() {
    local name="$1" desc="$2" default="${3:-}"
    local val
    val="$(eval echo \$$name 2>/dev/null || true)"
    if [ -z "$val" ]; then
      echo "  $name is not set"
      echo "    -> $desc"
      [ -n "$default" ] && echo "    (default: $default)"
      MISSING="$MISSING $name"
      return 1
    else
      echo "  $name is set"
      return 0
    fi
  }

  # `|| true` on purpose: check_var returns 1 for an unset var, and under
  # `set -e` a bare call would exit the wizard before showing the menu.
  check_var "ANTHROPIC_API_KEY" "Only if using Claude (chat model)" || true
  check_var "OPENAI_API_KEY" "Only if using DeepSeek/GPT-4o" || true

  echo ""
  if [ -z "$MISSING" ]; then
    echo "  All set. Run: ai-stack start"
    echo "  (No .env written — keys are already in your environment; copy .env.example.md to .env if you want one.)"
    exit 0
  fi

  echo "  Missing some vars. Pick how to provide them:"
  echo ""
  echo "  1) Print export commands (copy-paste into terminal)"
  echo "  2) Save to .env file (auto-loaded by docker compose)"
  echo "  3) Both"
  echo ""
  printf "  Choose [1/2/3] (default: 1): "
  read -r CHOICE
  CHOICE="${CHOICE:-1}"

  case "$CHOICE" in
    2|3)
      ENV_FILE="$DIR/.env"
      echo "# perfect-ai-stack" > "$ENV_FILE"
      echo "# Generated by: ai-stack wizard" >> "$ENV_FILE"
      echo "" >> "$ENV_FILE"
      ;;
  esac

  prompt_var() {
    local name="$1" desc="$2" default="${3:-}"
    local val
    val="$(eval echo \$$name 2>/dev/null || true)"
    if [ -n "$val" ]; then
      echo "  $name is set (environment)"
      case "$CHOICE" in
        2|3)
          echo "$name=\"$val\"" >> "$ENV_FILE"
          echo "  Saved to .env"
          ;;
      esac
      return 0
    fi

    if [ -n "$default" ]; then
      printf "  %s (%s) [%s]: " "$name" "$desc" "$default"
    else
      printf "  %s (%s): " "$name" "$desc"
    fi
    read -r INPUT
    INPUT="${INPUT:-$default}"
    if [ -z "$INPUT" ] && [ -z "$default" ]; then
      echo "    Skipped"
      case "$CHOICE" in
        2|3)
          echo "# $name=" >> "$ENV_FILE"
          ;;
      esac
      return 0
    fi

    case "$CHOICE" in
      1|3)
        echo ""
        echo "  Run this in your terminal:"
        echo "    export $name=\"$INPUT\""
        echo ""
        ;;
    esac
    case "$CHOICE" in
      2|3)
        echo "$name=\"$INPUT\"" >> "$ENV_FILE"
        echo "  Saved to .env"
        ;;
    esac
  }

  prompt_var "ANTHROPIC_API_KEY" "Only if using Claude (chat model)" ""
  prompt_var "OPENAI_API_KEY" "Only if using DeepSeek/GPT-4o" ""

  echo ""
  if [ "$CHOICE" != "1" ]; then
    echo "  Done! .env written to $DIR/.env"
  else
    echo "  Done!"
  fi
}

check_deps() {
  command -v docker >/dev/null 2>&1 || { echo "Missing: docker"; exit 1; }
}

# Install the git pre-commit hook that runs `lat check` on every commit in
# the given project. Idempotent: creates .git/hooks/pre-commit if missing,
# appends `lat check` to an existing hook that lacks it, skips if already
# present. Skipped (with a notice) when the target is not a git repository.
install_lat_hook() {
  local target="$1"
  if [ ! -d "$target/.git" ]; then
    echo "  (not a git repository — skipping pre-commit hook)"
    return 0
  fi
  local hook="$target/.git/hooks/pre-commit"
  if [ ! -f "$hook" ]; then
    mkdir -p "$(dirname "$hook")"
    cp "$DIR/scripts/pre-commit-hook.sh" "$hook"
    chmod +x "$hook"
    echo "  pre-commit hook installed (.git/hooks/pre-commit)"
  elif ! grep -q "lat check" "$hook" 2>/dev/null; then
    printf '\n# lat.md validation\n' >> "$hook"
    printf 'exec lat check 2>&1\n' >> "$hook"
    echo "  pre-commit hook updated (appended lat check)"
  else
    echo "  pre-commit hook already runs lat check"
  fi
}

# Scaffold lat.md + the pre-commit hook into a TARGET project. One clone of
# this package serves every repo:
#   cd some/project && sh /path/to/perfect-ai-stack/bin/ai-stack.sh setup-lat
# `lat init` is interactive (it asks which coding agents you use), so it only
# runs when stdin is a TTY; an unattended run prints a hint instead. Pass
# "strict" as $2 to fail the command when `lat check` fails (used by the
# explicit setup-lat command).
setup_lat() {
  local target="${1:-$PWD}"
  local strict="${2:-}"

  # 1. Install lat if missing (single global copy, shared by all projects)
  command -v lat >/dev/null 2>&1 || npm install -g lat.md

  # 2. Scaffold lat.md/ — `lat init` is interactive (it asks which coding
  #    agents you use), so it only runs when stdin is a TTY; an unattended
  #    run prints a hint instead. Runs when lat.md/ is missing or still
  #    contains only the committed placeholder intro file.
  if [ ! -d "$target/lat.md" ] || [ "$(find "$target/lat.md" -type f 2>/dev/null | wc -l | tr -d ' ')" = "1" ]; then
    if [ -t 0 ]; then
      lat init "$target"
    else
      echo "  lat.md not initialized in $target — run 'ai-stack setup-lat' interactively"
    fi
  fi

  # 3. Git pre-commit hook — `lat check` blocks commits with doc drift
  install_lat_hook "$target"

  # 4. .gitignore hygiene
  local gitignore="$target/.gitignore"
  if [ -f "$gitignore" ]; then
    for entry in "lat.md/.cache/" "lat.md/node_modules/"; do
      if ! grep -qF "$entry" "$gitignore"; then
        printf '%s\n' "$entry" >> "$gitignore"
        echo "  .gitignore: added $entry"
      fi
    done
  else
    printf 'lat.md/.cache/\nlat.md/node_modules/\n' > "$gitignore"
    echo "  .gitignore: created with lat entries"
  fi

  # 5. Verify — soft during start (docs are a quality gate, not a runtime
  #    gate), strict on explicit `ai-stack setup-lat`.
  if (cd "$target" && lat check >/dev/null 2>&1); then
    echo "  lat check: OK"
  else
    echo "  lat check: FAILED — fix the graph, then re-run"
    if [ "$strict" = "strict" ]; then
      return 1
    fi
  fi
}

case "$CMD" in
  wizard|setup|config)
    wizard
    ;;
  start|up)
    check_deps
    cd "$DIR"
    mkdir -p data/lore data/headroom

    echo "Building + starting LiteLLM (with Headroom) and Lore (Docker)..."
    docker compose up -d --build
    setup_lat "$DIR"
    echo ""
    echo "  LiteLLM -> http://localhost:4000"
    echo "  Lore    -> http://localhost:3207 (dashboard: /ui)"
    echo ""
    echo "Stack is running. Stop with: ai-stack stop"
    ;;
  stop|down)
    cd "$DIR"
    docker compose down
    echo "Done"
    ;;
  restart)
    "$0" stop
    sleep 1
    "$0" start
    ;;
  logs)
    cd "$DIR" && docker compose logs -f ${2:-}
    ;;
  ps|status)
    cd "$DIR" && docker compose ps
    ;;
  update)
    cd "$DIR"
    docker compose build --pull litellm lore
    echo "Done. Run ai-stack start to use the new versions."
    ;;
  setup-lat)
    setup_lat "${2:-$PWD}" strict
    ;;
  help|*)
    echo "perfect-ai-stack — AI proxy stack"
    echo ""
    echo "Commands:"
    echo "  wizard     Interactive setup for env vars"
    echo "  start      Build + start LiteLLM (with Headroom) + Lore (Docker)"
    echo "  stop       Stop both"
    echo "  restart    Restart both"
    echo "  logs       Follow logs (all services; pass a name for one)"
    echo "  ps         Show status"
    echo "  update     Rebuild LiteLLM (with Headroom) + Lore from latest base images"
    echo "  setup-lat  Scaffold lat.md + hook in [dir] (default: cwd; runs on start too)"
    echo ""
    echo "  sh bin/ai-stack.sh wizard"
    echo "  sh bin/ai-stack.sh start"
    echo "  cd some/project && sh /path/to/ai-stack/bin/ai-stack.sh setup-lat"
    echo ""
    echo "Quick start:"
    echo "  sh bin/ai-stack.sh wizard"
    echo "  sh bin/ai-stack.sh start"
    ;;
esac
